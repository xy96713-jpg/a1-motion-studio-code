import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import crypto from 'node:crypto';
import { stepStills, stillsGroup } from '../apps/studio-next/src/lib/recipe-board/stills.mjs';
import { readTask, submitTaskAnswer } from '../apps/studio-next/src/lib/recipe-board/agenttask.mjs';
const repo = path.resolve(import.meta.dirname, '..');
const hash = s => crypto.createHash('sha256').update(s).digest('hex');
test('explicit non-hero tasks stay isolated and never enter unchecked render', async t => {
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'stills-target-')); t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
 const dataDir=path.join(root,'work/recipe-board-v1'), p=path.join(dataDir,'projects/fixture');
 fs.cpSync(path.join(repo,'work/recipe-board-v1/routing'),path.join(dataDir,'routing'),{recursive:true});
 const put=(f,v)=>{const q=path.join(p,f);fs.mkdirSync(path.dirname(q),{recursive:true});fs.writeFileSync(q,typeof v==='string'?v:JSON.stringify(v));};
 const ids=Array.from({length:20},(_,i)=>`B${String(i+1).padStart(2,'0')}`);
 const beats=ids.map(id=>({id,text:`完整 ${id} 文案`}));
 const rows=ids.map((beat,i)=>({beat,hero:i<5 && i!==1 && i!==2 || i===5 || i===6}));
 put('project.json',{id:'fixture',agents:{default:'manual'}}); put('plan.json',{beats});
 for(const id of ids) put(`shots/${id}.json`,{shotId:id,recipe:'morph-chapter',motion:{duration:6}});
 const design=JSON.stringify({arc:'synthetic',beats:rows}); put('tasks/filmdesign.answer.json',design); put('tasks/filmdesign.check.json',{ok:true,answerHash:hash(design).slice(0,16)});
 const cfg={repoRoot:root,sourceRoot:root,dataDir};
 const run=targetBeat=>stepStills(cfg,'fixture',{targetBeat,log(){}});
 const a=await run('B02'), b=await run('B03');
 assert.equal(a.state,'waiting'); assert.equal(b.state,'waiting');
 const task2=readTask(cfg,'fixture','stills-B02'), task3=readTask(cfg,'fixture','stills-B03');
 assert.deepEqual(task2.input.beats.map(x=>[x.shotId,x.text,x.dur]),[['B02','完整 B02 文案',6]]);
 assert.deepEqual(task3.input.beats.map(x=>[x.shotId,x.text,x.dur]),[['B03','完整 B03 文案',6]]);
 put('out/chapters/STILLS-B03/assets/existing.png','previous-asset'); put('tasks/stills-B03.notes.json','previous-notes');
 const protectedFiles=['tasks/stills-B03.task.json','out/chapters/STILLS-B03/assets/existing.png','tasks/stills-B03.notes.json'];
 const before=protectedFiles.map(f=>hash(fs.readFileSync(path.join(p,f))));
 const candidate=path.join(root,'candidate.json'); fs.writeFileSync(candidate,JSON.stringify({sourceTaskInputHash:task2.inputHash,code:'// test'}));
 submitTaskAnswer(cfg,'fixture','stills-B02',candidate,{env:{CODEX_THREAD_ID:'fixture-writer'}});
 const result=await run('B02'); assert.equal(result.state,'rejected'); assert.match(result.errors.join(' '),/missing export/i);
 assert.deepEqual(protectedFiles.map(f=>hash(fs.readFileSync(path.join(p,f)))),before);
 assert.equal(JSON.parse(fs.readFileSync(path.join(p,'tasks/stills-B02.check.json'))).ok,false);
 const grouped=stillsGroup({beats:rows},beats.map(x=>({beat:x.id,text:x.text,dur:6}))); assert.equal(grouped.shots.length,5);
 await assert.rejects(()=>run('../escape'),/target/i); await assert.rejects(()=>run('B99'),/target/i);
});
