import assert from 'node:assert/strict';
import { decide, effectiveGate, loadMainline, mainlineCheck } from './mainline.mjs';
import { scaffoldDesignBoard, validateDesignBoard } from './design-gate.mjs';
const dirs = [
  ['A','specimen lineup','footage','real'],['B','one vs many','3d','3d'],['C','type as clone','graphic','graphic'],
  ['D','paper cut orchard','procedural','procedural'],['E','shelf corridor','3d','3d'],['F','print registry','graphic','graphic'],
];
