v2.directions[0].techStack = ['webgl-three'];
v2.directions[0].effects = ['camera-parallax'];
v2.directions[0].benchmark = { id: 'B12-old-card', status: 'pass', scores: { composition: 4, subject: 4, material: 4, typeLayout: 4, light: 4, texture: 4 } };
v2.directions[0].buildPlan = { contract: 'A1BuildPlan/v1', status: 'ready' };
assert.deepEqual(validateDesignBoard(v2), []);
const aiBad = JSON.parse(JSON.stringify(v2));
Object.assign(aiBad.directions[0], { role: 'optional-evidence', build: 'ai-video', reproduction: { mode: 'ai-video', fidelity: 'medium' }, aiVideoApproval: { status: 'approved' }, aiVideoDurationSec: 5, triage: { verdict: 'ai-video' } });
assert.ok(validateDesignBoard(aiBad).some((e) => e.includes('AI video is not allowed')));
const aiGood = JSON.parse(JSON.stringify(v2));
Object.assign(aiGood.directions[0], { role: 'main-spine', build: 'ai-video', techStack: ['ai-video'], techApproval: { 'ai-video': 'approved' }, reproduction: { mode: 'ai-video', fidelity: 'medium' }, aiVideoApproval: { status: 'approved' }, aiVideoDurationSec: 5, triage: { verdict: 'ai-video' } });
assert.deepEqual(validateDesignBoard(aiGood), []);
const v2BadWorld = JSON.parse(JSON.stringify(v2)); v2BadWorld.world.name = 'TODO: world';
assert.ok(validateDesignBoard(v2BadWorld).some((e) => e.includes('world.name')));
const v2BadTest = JSON.parse(JSON.stringify(v2)); v2BadTest.worldTest = { file: 'package.json', durationSec: 3, blindReview: { status: 'fail' } };
assert.ok(validateDesignBoard(v2BadTest).some((e) => e.includes('worldTest durationSec')));
const dup = JSON.parse(JSON.stringify(good)); dup.directions[1].thesis = dup.directions[0].thesis;
assert.ok(validateDesignBoard(dup).some((e) => e.includes('duplicates')));
const oneMedium = JSON.parse(JSON.stringify(good)); oneMedium.directions.forEach((d) => d.medium = '3d');
assert.ok(validateDesignBoard(oneMedium).some((e) => e.includes('at least 2 media')));
const draft = scaffoldDesignBoard({ project: 'x', line: 'y' });
assert.equal(draft.directions.length, 6);
assert.ok(validateDesignBoard(draft).length > 0);
const noLock = JSON.parse(JSON.stringify(good)); delete noLock.lookLock;
assert.ok(validateDesignBoard(noLock).some((e) => e.includes('lookLock missing')));
const few = JSON.parse(JSON.stringify(good)); few.directions = few.directions.slice(0,3);
assert.ok(validateDesignBoard(few).some((e) => e.includes('at least 6')));
const badRule = JSON.parse(JSON.stringify(good)); badRule.lookLock.rules = ['composition'];
assert.ok(validateDesignBoard(badRule).some((e) => e.includes('lookLock missing rule')));
const ws = JSON.parse(JSON.stringify(good)); ws.worldSheet = { contract: 'A1WorldSheet/v1', source: 'package.json', panels: [{index:1},{index:2},{index:3},{index:4},{index:5},{index:6}], ok: true };
assert.deepEqual(validateDesignBoard(ws), []);
const wsBad = JSON.parse(JSON.stringify(ws)); wsBad.worldSheet.panels = wsBad.worldSheet.panels.slice(0, 5);
assert.ok(validateDesignBoard(wsBad).some((e) => e.includes('worldSheet needs at least')));
console.log('design gate tests pass');
const cfg = loadMainline();
assert.equal(cfg.contract, 'A1Mainline/v1');
assert.ok(cfg.authorities.some((a) => a.role === 'design-preflight'));
const rejected = effectiveGate({ design: { approved: true } }, { decisions: [{ gate: 'design', status: 'rejected', reason: 'x' }] }, 'design');
assert.equal(rejected.status, 'rejected');
const approved = effectiveGate({ design: { approved: true, by: 'u', at: 't' } }, { decisions: [] }, 'design');
assert.equal(approved.status, 'approved');
