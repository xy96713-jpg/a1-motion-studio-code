assert.equal(denied.ok, false);
assert.ok(denied.errors.some((e) => e.includes('design board') && (e.includes('TODO') || e.includes('missing') || e.includes('frame'))));
const generated = JSON.parse(JSON.stringify(good)); generated.directions[0].frame = 'work/recipe-board-v1/style-lab/banana-3d/b01-art/shelf.png';
