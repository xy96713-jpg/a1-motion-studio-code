import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import crypto from 'node:crypto';
import { stepStills } from '../apps/studio-next/src/lib/recipe-board/stills.mjs';
import { submitTaskAnswer, readTask } from '../apps/studio-next/src/lib/recipe-board/agenttask.mjs';
const repo = path.resolve(import.meta.dirname, '..');
const digest = s => crypto.createHash('sha256').update(s).digest('hex').slice(0,16);
function fixture(t) {
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'stills-submission-')); t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
 const dataDir=path.join(root,'work/recipe-board-v1'), p=path.join(dataDir,'projects/fixture');
 fs.cpSync(path.join(repo,'work/recipe-board-v1/routing'),path.join(dataDir,'routing'),{recursive:true});
 const put=(f,v)=>{const q=path.join(p,f);fs.mkdirSync(path.dirname(q),{recursive:true});fs.writeFileSync(q,typeof v==='string'?v:JSON.stringify(v));};
 put('project.json',{id:'fixture',lettering:'fixture-lettering',agents:{default:'manual'}}); put('plan.json',{beats:[{id:'B01',text:'test'},{id:'B02',text:'other'}]});
 for(const id of ['B01','B02']) put(`shots/${id}.json`,{shotId:id,recipe:'morph-chapter',motion:{duration:5}});
 const design=JSON.stringify({arc:'synthetic',beats:[{beat:'B01',hero:true},{beat:'B02',hero:false}]});
 put('tasks/filmdesign.answer.json',design); put('tasks/filmdesign.check.json',{ok:true,answerHash:digest(design)});
 return {root,p,put,cfg:{repoRoot:root,sourceRoot:root,dataDir}};
}
test('current writer submission gates costly still work and preserves historical preview',async t=>{
 const {root,p,put,cfg}=fixture(t), run=()=>stepStills(cfg,'fixture',{log(){}});
 assert.equal((await run()).state,'waiting');
 const task=readTask(cfg,'fixture','stills');
 const candidate={sourceTaskInputHash:task.inputHash,code:'// isolated fixture',art:[{key:'absent',file:'absent.png'}]};
 put('tasks/stills.answer.json',JSON.stringify(candidate));
 put('out/old.png','historical preview'); put('tasks/stills.check.json',{ok:true,answerHash:'old',keyframes:['out/old.png'],assets:{}});
 put('shots/B02.json',JSON.stringify({shotId:'B02',sentinel:'unchanged'})); const other=fs.readFileSync(path.join(p,'shots/B02.json'));
 const oldCheck=fs.readFileSync(path.join(p,'tasks/stills.check.json'));
 const priorLettering=process.env.RB_LETTERING; t.after(()=>{if(priorLettering===undefined) delete process.env.RB_LETTERING; else process.env.RB_LETTERING=priorLettering;}); process.env.RB_LETTERING='preflight-sentinel';
 const blocked=async label=>{const before=fs.readdirSync(path.join(p,'out'),{recursive:true}).sort();const r=await run();assert.equal(r.state,'waiting',label);assert.equal(process.env.RB_LETTERING,'preflight-sentinel',label+' changed font state');assert.deepEqual(r.keyframes,[path.join(p,'out/old.png')]);assert.deepEqual(fs.readFileSync(path.join(p,'tasks/stills.check.json')),oldCheck);assert.deepEqual(fs.readFileSync(path.join(p,'shots/B02.json')),other);assert.deepEqual(fs.readdirSync(path.join(p,'out'),{recursive:true}).sort(),before,label+' wrote output');};
 fs.unlinkSync(path.join(p,'tasks/stills.answer.json')); await blocked('missing answer');
 put('tasks/stills.answer.json','not-json'); await blocked('malformed answer');
 put('tasks/stills.answer.json',JSON.stringify({...candidate,hairline:{invalid:true}})); await blocked('unsubmitted hairline');
 put('tasks/stills.answer.json',JSON.stringify(candidate)); await blocked('unsubmitted');
 const candidateFile=path.join(root,'candidate.json');fs.writeFileSync(candidateFile,JSON.stringify(candidate));
 submitTaskAnswer(cfg,'fixture','stills',candidateFile,{env:{CODEX_THREAD_ID:'fixture-writer'}});
 fs.unlinkSync(path.join(p,'tasks/stills.task.json')); await blocked('missing task'); await blocked('regenerated task does not revive old receipt');
 submitTaskAnswer(cfg,'fixture','stills',candidateFile,{env:{CODEX_THREAD_ID:'fixture-writer'}});
 put('tasks/stills.answer.json',JSON.stringify({...candidate,code:'// replaced'})); await blocked('answer bytes replaced');
 fs.writeFileSync(path.join(p,'tasks/stills.answer.json'),JSON.stringify(candidate));
 put('plan.json',{beats:[{id:'B01',text:'changed task input'},{id:'B02',text:'other'}]}); await blocked('task input changed');
 const updated=readTask(cfg,'fixture','stills'); assert.notEqual(updated.inputHash,task.inputHash);
 fs.writeFileSync(candidateFile,JSON.stringify({...candidate,sourceTaskInputHash:updated.inputHash}));
 submitTaskAnswer(cfg,'fixture','stills',candidateFile,{env:{CODEX_THREAD_ID:'fixture-writer'}});
 const result=await run(); assert.equal(result.state,'rejected',JSON.stringify(result));
 assert.equal(process.env.RB_LETTERING,'fixture-lettering','valid submission reaches real lettering setup');
 assert.match(result.errors.join(' '),/absent|missing/i,'valid submission reached real preparation and missing-file check');
 assert.deepEqual(fs.readFileSync(path.join(p,'shots/B02.json')),other);
});
