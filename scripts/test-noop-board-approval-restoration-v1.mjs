import fs from "node:fs";
import assert from "node:assert/strict";
import {approveWholeFilmStaticBoardAndQueueLayerReconstruction as approve} from "../apps/studio-next/src/lib/a1-whole-film-look-master-production-v1.mjs";
import {applyCurrentStoryboardShotPatch} from "../apps/studio-next/src/lib/a1-current-storyboard-editor-v1.mjs";
import {motionReviewSource} from "../apps/studio-next/src/lib/a1-shot-motion-review-v1.mjs";

const workspace = JSON.parse(fs.readFileSync(new URL("../apps/studio-next/public/generated/system-line/editorial-asset-workbench-v1/workspace.json", import.meta.url)));
const broken = structuredClone(workspace), runtime = broken.production.shotIntelligence;
assert.equal(runtime.wholeFilmStaticBoard.status, "APPROVED");
runtime.wholeFilmStaticBoard.status = "PENDING_USER_APPROVAL";
runtime.currentStoryboardAuthority.userVisualApproval = "NOT_APPROVED";
runtime.wholeFilmBatchRecommendation.nextUserGate = "WHOLE_FILM_STATIC_BOARD";
broken.production.visualProductionRun.status = "WHOLE_FILM_STATIC_BOARD_READY";
const shot = runtime.currentStoryboardAuthority.shots.find((item) => item.prototypeEligible && item.motionReviewPlan);
const proof = {contract: "A1VerifiedNoOpStoryboardEdit/v1", lastEventId: broken.production.eventLedger.lastEventId, priorAuditSha256: "1".repeat(64), boardSha256: runtime.wholeFilmStaticBoard.sha256, shotId: shot.shotId, source: motionReviewSource(shot)};
const args = {expectedWorkspaceSha256: broken.workspaceSha256, expectedBoardSha256: runtime.wholeFilmStaticBoard.sha256, expectedBoardItemSeedSha256: runtime.wholeFilmStaticBoard.itemSeedSha256, approvalAuthority: runtime.wholeFilmStaticBoard.approvalAuthority};
assert.throws(() => approve(broken, args), /approval-stage-invalid/);
const restored = approve(broken, {...args, restoreNoOpEdit: proof});
assert.equal(restored.workspace.production.shotIntelligence.wholeFilmStaticBoard.status, "APPROVED");
assert.equal(restored.workspace.production.shotIntelligence.wholeFilmStaticBoard.decisionSha256, runtime.wholeFilmStaticBoard.decisionSha256);
assert.equal(restored.jobs.length, 0);
assert.equal(restored.workspace.production.generation.automaticDispatchAllowed, false);
const changed = applyCurrentStoryboardShotPatch(broken, {shotId: shot.shotId, sourceText: "A genuinely changed narration"});
assert.throws(() => approve(changed, {...args, restoreNoOpEdit: proof}), /restoration-unproven|motion-review-stale/);
assert.throws(() => approve(broken, {...args, restoreNoOpEdit: {...proof, lastEventId: "not-current"}}), /restoration-unproven/);
const changedDecision = structuredClone(broken);
changedDecision.production.shotIntelligence.wholeFilmStaticBoard.decisionSha256 = "0".repeat(64);
assert.throws(() => approve(changedDecision, {...args, restoreNoOpEdit: proof}), /decision-changed/);
console.log("PASS: verified no-op restores identical decision without dispatch; real edits, stale events and changed decisions reject");
