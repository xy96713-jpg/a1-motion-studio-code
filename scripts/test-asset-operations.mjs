import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
const M = await import('../apps/studio-next/src/lib/recipe-board/assetoperations.mjs').catch(() => ({}));
assert.equal(typeof M.assetOperationPreflight, 'function', 'real asset operation preflight is required');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'asset-operation-'));
try {
  const result = await M.assetOperationPreflight({ root, beats: [{ beat: 'B01', directorIntent: { assets: [{ id: 'subject', file: '/does-not-exist.png', operation: 'per-object', operability: 'layers' }] } }] });
  assert.match(result.errors.join(), /missing|ENOENT/);
  const sharp = createRequire(new URL('../apps/studio-next/package.json', import.meta.url))('sharp');
  const crypto = await import('node:crypto');
  const digest = f => crypto.createHash('sha256').update(fs.readFileSync(path.join(root, f))).digest('hex');
  await sharp({ create: { width: 2, height: 2, channels: 4, background: '#ff0000' } }).png().toFile(path.join(root, 'art.png'));
  const a = { id: 'subject', use: 'art', source: 'generated', file: 'art.png', sha256: digest('art.png'), operation: 'hold', operability: 'whole-image' };
  const check = (asset, options = {}) => M.assetOperationPreflight({ root, beats: [{ beat: 'B01', directorIntent: { assets: [asset] } }], ...options });
  assert.deepEqual((await check(a)).errors, [], 'a static illustrative image is legal');
  const code = "export function fg(g,t,cam,moves,where,type){type.flat.typeBlock(g,{x:120,y:270,lines:[{text:'辨認',size:300}]});}";
  const codeAsset = { id: 'title', use: 'type', source: 'code', file: 'module:fg', sha256: crypto.createHash('sha256').update(code).digest('hex'), operation: 'hold', operability: 'code', targets: ['type.flat.typeBlock'] };
  assert.deepEqual((await check(codeAsset, { code })).errors, [], 'static code type group binds executable consumer and full module hash');
  const deadCode = code.replace('{type.flat', '{return;type.flat');
  assert.match((await check({ ...codeAsset, sha256: crypto.createHash('sha256').update(deadCode).digest('hex') }, { code: deadCode })).errors.join(), /target/, 'unreachable calls are not consumption anchors');
  fs.writeFileSync(path.join(root, 'code.mjs'), 'export const fixture = true;');
  assert.match((await check({ ...a, file: 'code.mjs', sha256: digest('code.mjs'), source: 'code', operability: 'code' })).errors.join(), /unknown asset capability/, 'code declarations are not file-backed capability proof');
  assert.match((await check({ ...a, file: 'not-generated-yet.png' })).errors.join(), /ENOENT/, 'planned generation cannot satisfy a current-byte pin');
  assert.match((await check({ ...a, operation: 'per-object', operability: 'layers', targets: ['banana'], layers: ['banana'] })).errors.join(), /capability|whole-image|layers/);
  assert.match((await check({ ...a, sha256: '0'.repeat(64) })).errors.join(), /hash/);
  assert.match((await check({ ...a, sha256: undefined })).errors.join(), /hash/);
  assert.match((await check({ ...a, use: 'evidence' })).errors.join(), /evidence/);
  assert.match((await check({ ...a, use: 'evidence', source: 'real', provenance: 'https://example.com' })).errors.join(), /binding/);
  const real = { ...a, use: 'evidence', source: 'real', provenance: 'https://example.com/photo' };
  const bindings = { shots: { B01: { file: path.join(root, 'art.png'), url: real.provenance, sha256: a.sha256 } } };
  assert.deepEqual((await check(real, { bindings })).errors, []);
  assert.match((await check(real, { bindings, generatedFiles: ['art.png'] })).errors.join(), /generated/);
  assert.match((await check(a, { consumedFiles: [] })).errors.join(), /consumer/);
  assert.deepEqual((await check(a, { consumedFiles: ['art.png'] })).errors, []);
  assert.deepEqual((await check(a, { shotIds: ['B99'] })).errors, [], 'unrelated shots stay compatible');
  fs.writeFileSync(path.join(root, 'layers.json'), JSON.stringify({ contract: 'A1AssetLayers/v1', layers: [{ id: 'banana', file: 'art.png', sha256: a.sha256 }] }));
  const layers = { ...a, file: 'layers.json', sha256: digest('layers.json'), operation: 'per-object', operability: 'layers', targets: ['banana'] };
  assert.deepEqual((await check(layers)).errors, []);
  assert.match((await check({ ...layers, targets: ['missing'] })).errors.join(), /target/);
  assert.match((await check({ ...layers, targets: [] })).errors.join(), /target/);
  assert.match((await check({ ...layers, operation: 'deform' })).errors.join(), /unknown/);
  // Real minimal GLB: one reachable triangle node with actual binary positions.
  const gltf = { asset: { version: '2.0' }, scene: 0, scenes: [{ nodes: [0] }], nodes: [{ name: 'banana', mesh: 0 }], meshes: [{ primitives: [{ attributes: { POSITION: 0 } }] }], accessors: [{ bufferView: 0, componentType: 5126, count: 3, type: 'VEC3' }], bufferViews: [{ buffer: 0, byteOffset: 0, byteLength: 36 }], buffers: [{ byteLength: 36 }] };
  const json = Buffer.from(JSON.stringify(gltf).padEnd(Math.ceil(JSON.stringify(gltf).length / 4) * 4, ' '));
  const bin = Buffer.from(new Float32Array([0, 0, 0, 1, 0, 0, 0, 1, 0]).buffer);
  const glb = Buffer.alloc(28 + json.length + bin.length);
  glb.writeUInt32LE(0x46546c67, 0); glb.writeUInt32LE(2, 4); glb.writeUInt32LE(glb.length, 8);
  glb.writeUInt32LE(json.length, 12); glb.writeUInt32LE(0x4e4f534a, 16); json.copy(glb, 20);
  glb.writeUInt32LE(bin.length, 20 + json.length); glb.writeUInt32LE(0x004e4942, 24 + json.length); bin.copy(glb, 28 + json.length);
  fs.writeFileSync(path.join(root, 'model.glb'), glb);
  const model = { ...layers, file: 'model.glb', sha256: digest('model.glb'), operability: 'mesh' };
  assert.deepEqual((await check(model)).errors, [], 'real GLB mesh node is operable');
  const pendingModel = { ...model, file: 'model:triangle', sha256: 'pending' };
  const productions = [{ reference: 'model:triangle', prompt: 'a triangle mesh', capability: 'mesh', consumed: true }];
  const admittedModel = await check(pendingModel, { phase: 'prepare', productions });
  assert.deepEqual(admittedModel.errors, []);
  assert.equal(admittedModel.pending.length, 1);
  assert.deepEqual(admittedModel.evidence, [], 'admission is not final capability evidence');
  assert.match((await check(pendingModel, { productions })).errors.join(), /final pinned/);
  const resolved = [{ beat: 'B01', id: model.id, reference: 'model:triangle', file: path.join(root, 'model.glb'), sha256: model.sha256 }];
  assert.deepEqual((await check(pendingModel, { productions, resolved })).errors, []);
  assert.match((await check({ ...pendingModel, targets: ['missing'] }, { productions, resolved })).errors.join(), /target/);
  assert.match((await check({ ...pendingModel, targets: [] }, { phase: 'prepare', productions })).errors.join(), /target/);
  assert.match((await check({ ...model, targets: ['absent'] })).errors.join(), /target/);
  glb.writeUInt32LE(0, 8); fs.writeFileSync(path.join(root, 'model.glb'), glb);
  assert.match((await check({ ...model, sha256: digest('model.glb') })).errors.join(), /GLB/);
  // Exercise prepareAssets itself; invalid operations must return before generation.
  const C = await import('../apps/studio-next/src/lib/recipe-board/chapter.mjs');
  const cfg = { repoRoot: root, sourceRoot: path.resolve(import.meta.dirname, '..'), dataDir: path.join(root, 'data') };
  const project = path.join(cfg.dataDir, 'projects/test');
  fs.mkdirSync(path.join(project, 'tasks'), { recursive: true });
  fs.writeFileSync(path.join(project, 'project.json'), '{}');
  const design = asset => {
    const text = JSON.stringify({ beats: [{ beat: 'B01', directorIntent: { assets: [asset] } }] });
    fs.writeFileSync(path.join(project, 'tasks/filmdesign.answer.json'), text);
    fs.writeFileSync(path.join(project, 'tasks/filmdesign.check.json'), JSON.stringify({ ok: true, answerHash: crypto.createHash('sha256').update(text).digest('hex').slice(0, 16) }));
  };
  design({ ...a, file: '/does-not-exist.png' });
  const group = { id: 'B01', shots: [{ shotId: 'B01' }] };
  const rejected = await C.prepareAssets(cfg, 'test', group, { code: '' }, { log: () => {} });
  assert.match(rejected.errors.join(), /asset-operation.*ENOENT/, 'real consumer rejects missing operation asset');
  fs.copyFileSync(path.join(root, 'art.png'), path.join(project, 'art.png'));
  design(a);
  const prepared = await C.prepareAssets(cfg, 'test', group, { code: 'images.subject', art: [{ key: 'subject', file: 'art.png' }] }, { log: () => {} });
  assert.deepEqual(prepared.errors, []);
  assert.equal(prepared.assets.subject, fs.realpathSync(path.join(project, 'art.png')));
  design({ ...a, operation: 'per-object', operability: 'layers', targets: ['banana'] });
  assert.match((await C.prepareAssets(cfg, 'test', group, { code: '', art: [{ key: 'subject', file: 'art.png' }] }, { log: () => {} })).errors.join(), /capability/);
  const pending = { ...a, file: 'art:subject', sha256: 'pending', targets: [] };
  const schema = JSON.parse(fs.readFileSync(path.resolve(import.meta.dirname, '../work/recipe-board-v1/routing/filmdesign.schema.json')));
  const branches = schema.properties.beats.items.properties.directorIntent.properties.assets.items.anyOf;
  assert.ok(branches.some(b => b.properties.sha256.enum?.includes('pending') && b.properties.source.enum?.join() === 'generated'), 'schema must admit explicit pending generation, not unpin existing files');
  design(pending);
  let generated = 0;
  const generationAnswer = { code: 'export function draw(g,item,p,t,x,y,sc,images){g.drawImage(images.subject,0,0);}', art: [{ key: 'subject', prompt: 'An illustrative red field' }] };
  const commentAnswer = { ...generationAnswer, code: 'export function draw(){/* images.subject */}' };
  const commentResult = await C.prepareAssets(cfg, 'test', group, commentAnswer, { log: () => {}, generateArt: () => { generated++; return { file: path.join(project, 'art.png') }; } });
  assert.equal(generated, 0, 'a comment is not a production consumer anchor');
  assert.match(commentResult.errors.join(), /binding/);
  const generatedResult = await C.prepareAssets(cfg, 'test', group, generationAnswer, { log: () => {}, generateArt: () => { generated++; return { file: path.join(project, 'art.png') }; } });
  assert.equal(generated, 1, 'pending demand must reach the actual art generation branch (isolated stub, no paid generation)');
  assert.deepEqual(generatedResult.errors, []);
  assert.equal(generatedResult.operationEvidence[0].sha256, a.sha256);
  assert.equal(generatedResult.operationEvidence[0].file, fs.realpathSync(path.join(project, 'art.png')));
  assert.deepEqual((await C.chapterAssetOperationCheck(cfg, 'test', group, generationAnswer.code, generatedResult.assets)).errors, []);
  fs.appendFileSync(path.join(project, 'art.png'), 'changed');
  const renderRejected = await C.runtimeCheck(cfg, 'test', group, generationAnswer.code, generatedResult.assets);
  assert.match(renderRejected.errors.join(), /asset-operation.*hash/, 'render must re-read bytes, not repin output or trust preparation');
  const beforeRetry = generated;
  const tamperedRetry = await C.prepareAssets(cfg, 'test', group, generationAnswer, { log: () => {}, generateArt: () => { generated++; return { file: path.join(project, 'art.png') }; } });
  assert.match(tamperedRetry.errors.join(), /hash/, 'repeat preparation cannot silently repin changed pending output');
  assert.equal(generated, beforeRetry);
  fs.copyFileSync(path.join(root, 'art.png'), path.join(project, 'art.png'));
  const failedGeneration = await C.prepareAssets(cfg, 'test', group, generationAnswer, { log: () => {}, generateArt: () => { throw new Error('isolated generation failure'); } });
  assert.match(failedGeneration.errors.join(), /isolated generation failure/);
  assert.match((await C.chapterAssetOperationCheck(cfg, 'test', group, generationAnswer.code, generatedResult.assets)).errors.join(), /pending/);
  assert.match((await check(codeAsset, { code: code + ' ' })).errors.join(), /hash/);
  assert.match((await check({ ...codeAsset, targets: ['type.flat.missing'] }, { code })).errors.join(), /target/);
  const commentCode = "export function fg(g,t,cam,moves,where,type){/* type.flat.typeBlock(g,{}) */}";
  assert.match((await check({ ...codeAsset, sha256: crypto.createHash('sha256').update(commentCode).digest('hex') }, { code: commentCode })).errors.join(), /target/);
  fs.appendFileSync(path.join(root, 'art.png'), 'changed');
  assert.match((await check(layers)).errors.join(), /hash/);
} finally { fs.rmSync(root, { recursive: true, force: true }); }
console.log('asset operations: PASS');
