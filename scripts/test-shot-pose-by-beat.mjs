import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { morphPoseFromScaleErrors } from '../apps/studio-next/src/lib/recipe-board/shotmotion.mjs';
const values = [1.08, 1.22, 1, 1];
const contract = { shots: values.map((s, i) => ({ shotId: `B${i}`, seam: { poseFrom: { s } }, subjectMotion: 'stagger' })) };
const code = `export const beats=[${values.map((s, i) => `{at:${i * 8},cam:{s:${s},x:960,y:540}}`).join(',')}];`;
assert.deepEqual(morphPoseFromScaleErrors(code, contract), []);
assert.deepEqual(morphPoseFromScaleErrors(code, contract, { shots: values.map((_, i) => ({ shotId: `B${i}`, at: i * 8, dur: 8 })) }), []);
const errors = morphPoseFromScaleErrors(code.replace('s:1.22', 's:1.08'), contract);
assert.equal(errors.length, 1);
assert.match(errors[0], /morph.B1.seam.poseFrom.inherit/);
const explicit = 'export const beats=[{at:0,camFrom:{s:1.08,x:960,y:520},cam:{s:1.22,x:920,y:540}},{at:8,camFrom:{s:1.22,x:920,y:540},cam:{s:1.22,x:920,y:540}}];';
assert.deepEqual(morphPoseFromScaleErrors(explicit, {shots:contract.shots.slice(0,2)}), []);
const template = fs.readFileSync(new URL('../work/recipe-board-v1/style-lab/engine/templates/morph.js', import.meta.url), 'utf8');
const camFn = template.slice(template.indexOf('function camAt(t)'), template.indexOf('const _dir =', template.indexOf('function camAt(t)')));
const beats = [{at:0,camFrom:{s:1.08,x:960,y:520},cam:{s:1.22,x:920,y:540},camMove:2},{at:8,camFrom:{s:1.22,x:920,y:540},cam:{s:1.22,x:920,y:540},camMove:1}];
const context = vm.createContext({S:{mod:{beats}}, EASE:{move:u=>u}, clamp01:u=>Math.max(0,Math.min(1,u)), lerp:(a,b,u)=>a+(b-a)*u, beatAt:t=>t>=8?1:0});
vm.runInContext(camFn, context);
assert.equal(vm.runInContext('camAt(0).s',context),1.08);
assert.equal(vm.runInContext('camAt(2).s',context),1.22);
assert.equal(vm.runInContext('camAt(8).s',context),1.22);
delete beats[0].camFrom; delete beats[1].camFrom;
assert.equal(vm.runInContext('camAt(0).s',context),1.22,'legacy first-beat behavior retained');
console.log('pose inheritance: each beat uses its own camera; a wrong second beat still fails');
