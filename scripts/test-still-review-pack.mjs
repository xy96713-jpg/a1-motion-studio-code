import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import sharp from '../apps/studio-next/node_modules/sharp/lib/index.js';
const moduleURL = new URL('../apps/studio-next/src/lib/recipe-board/still-review-pack.mjs', import.meta.url);
const scratch = path.join(os.homedir(), '.hermes/cache/scratch');
fs.mkdirSync(scratch, {recursive:true});
const dir = fs.mkdtempSync(path.join(scratch, 'still-review-pack-test-'));
await sharp({create:{width:192,height:108,channels:3,background:'#446688'}}).png().toFile(path.join(dir,'frame.png'));
fs.writeFileSync(path.join(dir,'input.json'),'{"fixture":true}');
test('a real decoded frame produces hashed roles, never an inspection or approval', async()=>{
 assert.ok(fs.existsSync(moduleURL), 'still review pack module must exist');
 const {buildStillReviewPack}=await import(moduleURL);
 const p=await buildStillReviewPack({root:dir,outDir:path.join(dir,'pack'),expectedBeats:['B01','B02'],inputFiles:['input.json'],shots:[{beat:'B01',frame:'frame.png'}]});
 assert.equal(p.shots[0].images['original-size'].width,192);
 assert.equal(p.shots[0].images.downscaled.sourceHash,p.shots[0].images['original-size'].hash);
 assert.equal(p.shots[0].images['layout-overlay'].status,'unknown');
 assert.deepEqual(p.coverage.missing,['B02']);
 assert.equal(p.complete,false);
 assert.equal(p.visualInspection,'unknown');
 assert.equal(p.aestheticVerdict,'not-assessed');
 assert.equal(p.shots[0].version.status,'unknown');
 assert.equal(p.shots[0].references.status,'unknown');
 assert.ok(fs.readFileSync(path.join(dir,'pack/review-checklist.md'),'utf8').includes('B02 — MISSING'));
 assert.equal(p.checklistScope,'Unanswered prompts for the existing review schema; not a review answer');
});
test('render binding, measured overlay and reference mapping are hash-bound; edits invalidate them',async()=>{
 const {buildStillReviewPack,verifyStillReviewPack}=await import(moduleURL);
 const opts={root:dir,outDir:path.join(dir,'bound'),expectedBeats:['B01'],inputFiles:['input.json'],shots:[{beat:'B01',frame:'frame.png'}]};
 const initial=await buildStillReviewPack(opts), frameHash=initial.shots[0].images['original-size'].hash;
 opts.shots[0].renderBinding={inputHash:initial.inputHash,frameHash};
 opts.shots[0].geometry={frameHash,method:'fixture ink boxes',boxes:[{id:'title',x:10,y:10,w:80,h:20},{id:'evidence',x:35,y:40,w:100,h:40}]};
 opts.shots[0].references=[{key:'fixture/ref',frame:'frame.png',source:'input.json',method:'one shared left axis',target:'title and evidence',evidence:{file:'input.json',locator:'fixture'}}];
 const p=await buildStillReviewPack(opts);
 assert.equal(p.shots[0].version.status,'bound');
 assert.equal(p.shots[0].images['layout-overlay'].status,'available');
 assert.equal(p.shots[0].measurements.crossElementGeometry.pairs[0].leftDelta,25);
 assert.equal(p.shots[0].references.items[0].status,'declared-linked-not-visually-verified');
 assert.equal(p.complete,true);
 assert.equal(p.visualInspection,'unknown');
 assert.equal(verifyStillReviewPack(p).ok,true);
 fs.appendFileSync(p.shots[0].images['layout-overlay'].path,'changed');
 assert.equal(verifyStillReviewPack(p).ok,false,'old/changed overlay must invalidate pack');
 opts.shots[0].geometry.frameHash='old';
 opts.shots[0].renderBinding.frameHash='old';
 const stale=await buildStillReviewPack(opts);
 assert.equal(stale.complete,false);
 assert.equal(stale.shots[0].version.status,'stale');
 assert.equal(stale.shots[0].images['layout-overlay'].status,'unknown');
 fs.writeFileSync(path.join(dir,'input.json'),'{"fixture":"changed"}');
 assert.equal(verifyStillReviewPack(p).ok,false,'old input must invalidate pack');
});
test('coverage uses beat identity; repeated assets/layout are notes not aesthetic gates',async()=>{
 const {buildStillReviewPack}=await import(moduleURL);
 const p=await buildStillReviewPack({root:dir,outDir:path.join(dir,'repeated'),expectedBeats:['B01','B02'],inputFiles:['input.json'],shots:[{beat:'B01',frame:'frame.png',assets:['frame.png'],layoutKey:'split'},{beat:'B01',frame:'frame.png',assets:['frame.png'],layoutKey:'split'}]});
 assert.deepEqual(p.coverage.duplicates,['B01']); assert.deepEqual(p.coverage.missing,['B02']);
 assert.ok(p.boardRisks.some(x=>x.kind==='repeated-asset'));
 assert.ok(p.boardRisks.some(x=>x.kind==='repeated-layout-declaration'));
 assert.equal(p.complete,false);
});
test('existing review task schema and receipt validator are reused without making a receipt',async()=>{
 const {buildStillReviewPack}=await import(moduleURL);
 const p=await buildStillReviewPack({root:dir,outDir:path.join(dir,'receipt'),expectedBeats:[],reviewBinding:{cfg:{dataDir:dir},project:'missing',step:'review',writerStep:'writer',task:{schema:'work/recipe-board-v1/routing/taste.schema.json',forAnswer:'not-a-real-answer'}}});
 assert.equal(p.reviewChain.schema,'work/recipe-board-v1/routing/taste.schema.json');
 assert.equal(p.reviewChain.status.ok,false);
 assert.equal(fs.existsSync(path.join(dir,'projects/missing/tasks/review.submission.json')),false);
});
