import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import * as C from '../apps/studio-next/src/lib/recipe-board/chapter.mjs';

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'chapter-production-binding-'));
try {
  const cfg = { repoRoot: tmp, sourceRoot: tmp, dataDir: path.join(tmp, 'work/recipe-board-v1') };
  const root = path.join(cfg.dataDir, 'projects/test'); fs.mkdirSync(root, { recursive: true });
  const put = (file, text) => { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, text); };
  put(path.join(root, 'project.json'), '{}');
  for (const f of ['AGENTS.md', 'SOP.md', '.codex/skills/recipe-board-director/SKILL.md']) put(path.join(tmp, f), 'authority');
  const inherited = C.chapterInheritance(cfg, 'test');
  assert.ok(inherited.files['repo:AGENTS.md'], 'AGENTS is a hashed production authority');
  assert.ok(inherited.files['repo:SOP.md']);
  assert.ok(inherited.files['repo:.codex/skills/recipe-board-director/SKILL.md']);
  put(path.join(tmp, 'SOP.md'), 'changed');
  assert.notDeepEqual(C.chapterInheritance(cfg, 'test').files, inherited.files);
  put(path.join(root, 'art.png'), 'locked frame');
  const input = { inheritance: { files: { HOUSE: 'hash' } }, userLocked: { B01: { file: 'art.png' } }, assets: [{ file: path.join(root, 'art.png') }] };
  assert.equal(typeof C.productionInputFiles, 'function', 'task references need byte bindings');
  const files = C.productionInputFiles(cfg, 'test', input);
  assert.equal(files.length, 1, 'same file is bound once');
  assert.ok(files[0].hash);
  put(path.join(root, 'art.png'), 'changed frame');
  assert.notDeepEqual(C.productionInputFiles(cfg, 'test', input), files);
  fs.unlinkSync(path.join(root, 'art.png'));
  assert.equal(C.productionInputFiles(cfg, 'test', input)[0].hash, null, 'missing referenced files are not silently dropped');
  assert.equal(typeof C.chapterAdmissionErrors, 'function', 'production consumer requires binding validation');
  put(path.join(root, 'art.png'), 'locked frame');
  put(path.join(tmp, 'guide.md'), 'guide');
  const crypto = await import('node:crypto');
  const hash = (s) => crypto.createHash('sha256').update(s).digest('hex').slice(0, 16);
  input.inheritance.productionFiles = C.productionInputFiles(cfg, 'test', input);
  const h = C.inputHash(input), answer = { sourceTaskInputHash: h };
  const task = { inputHash: h, input: { ...input, sourceTaskInputHash: h, handoffGuides: [{ path: 'guide.md', hash: hash('guide') }] } };
  const errors = (t = task, a = answer, prev = null, rec = null) => C.chapterAdmissionErrors(cfg, 'test', { input, task: t, answer: a, previousCheck: prev, answerHash: 'candidate', record: rec, requireHandoff: true });
  assert.deepEqual(errors(), []);
  assert.match(errors(null).join(), /task/);
  assert.match(errors({ ...task, inputHash: 'forged' }).join(), /task/);
  assert.match(errors(task, {}).join(), /bound/);
  assert.match(errors(task, {}, { answerHash: 'candidate', ok: false }).join(), /bound/, 'a failed check must not launder an unbound answer');
  put(path.join(tmp, 'guide.md'), 'changed');
  assert.match(errors().join(), /guide/);
  put(path.join(tmp, 'guide.md'), 'guide');
  put(path.join(root, 'art.png'), 'changed');
  assert.match(errors().join(), /production/);
  put(path.join(root, 'art.png'), 'locked frame');
  assert.match(errors({ ...task, input: { ...task.input, inheritance: {} } }).join(), /task/);
  const legacy = { answerHash: 'candidate', ok: true };
  assert.deepEqual(errors(null, { code: 'old code' }, legacy, { acceptedAt: 'old', codeHash: hash('old code') }), [], 'accepted historical answers do not require migration');
  assert.match(errors(null, {}, legacy, null).join(), /task/, 'checked but unaccepted work must enter through current task');
  // Real production consumer: a direct canonical answer must not reach prepareAssets/runtime.
  put(path.join(root, 'project.json'), JSON.stringify({ id: 'test', gateSet: 'design', process: 'six-stage', design: { approved: true }, profile: 'paperclip', agents: { default: 'manual' } }));
  put(path.join(root, 'shots/B01.json'), JSON.stringify({ shotId: 'B01', recipe: 'morph-chapter', motion: { duration: 5 } }));
  put(path.join(root, 'plan.json'), JSON.stringify({ beats: [{ id: 'B01', text: 'test' }] }));
  put(path.join(root, 'tasks/morph-B01.answer.json'), JSON.stringify({ code: 'invalid candidate must never execute' }));
  const logs = [];
  const result = await C.stepChapters(cfg, 'test', { review: false, renderDrafts: false, rounds: 1, log: (line) => logs.push(line) });
  assert.deepEqual(result.accepted, []);
  const checkPath = path.join(root, 'tasks/morph-B01.check.json');
  assert.ok(fs.existsSync(checkPath), `missing chapter check: ${JSON.stringify(result)}; task=${fs.existsSync(path.join(root, 'tasks/morph-B01.task.json'))}; logs=${JSON.stringify(logs)}`);
  const check = JSON.parse(fs.readFileSync(checkPath));
  assert.match(check.errors.join(), /chapter task/);
  assert.match(check.errors.join(), /submission/);
  assert.equal(fs.existsSync(path.join(root, 'tasks/morph-B01.checked.json')), false);
  assert.equal(fs.existsSync(path.join(root, 'chapters/B01.mjs')), false);
  // A normal writer submission clears this gate (invalid code still fails downstream).
  cfg.sourceRoot = path.resolve(import.meta.dirname, '..');
  const p = JSON.parse(fs.readFileSync(path.join(root, 'project.json'))); p.design.greybox = 'fixture';
  put(path.join(root, 'project.json'), JSON.stringify(p));
  put(path.join(root, 'tasks/greybox.check.json'), JSON.stringify({ ok: true, answerHash: 'fixture' }));
  put(path.join(root, 'tasks/greybox.answer.json'), JSON.stringify({ beats: [] }));
  C.refreshChapterTask(cfg, 'test', 'B01', { handoffGuides: ['guide.md'] });
  const taskFile = path.join(root, 'tasks/morph-B01.task.json');
  const currentTask = JSON.parse(fs.readFileSync(taskFile));
  const candidate = path.join(tmp, 'candidate.json');
  put(candidate, JSON.stringify({ sourceTaskInputHash: currentTask.inputHash, code: 'different invalid code' }));
  const A = await import('../apps/studio-next/src/lib/recipe-board/agenttask.mjs');
  A.submitTaskAnswer(cfg, 'test', 'morph-B01', candidate, { env: { CODEX_THREAD_ID: 'isolated-test-writer' } });
  await C.stepChapters(cfg, 'test', { review: false, renderDrafts: false, rounds: 1, log: () => {} });
  const checked = JSON.parse(fs.readFileSync(path.join(root, 'tasks/morph-B01.check.json')));
  assert.ok(checked.errors.length, 'invalid code remains invalid');
  assert.doesNotMatch(checked.errors.join(), /chapter task|not bound|submission|authority sources|production files|handoff guide/);
  assert.equal(fs.existsSync(path.join(root, 'tasks/morph-B01.checked.json')), true, 'submitted candidate entered the ordinary code checker');
  const malformed = JSON.parse(fs.readFileSync(taskFile)); malformed.input.handoffGuides = {};
  put(taskFile, JSON.stringify(malformed));
  assert.doesNotThrow(() => C.chapterState(cfg, 'test'), 'malformed guide binding is rejected, not a status crash');
  assert.equal(C.chapterState(cfg, 'test')[0].taskFresh, false);
} finally { fs.rmSync(tmp, { recursive: true, force: true }); }
console.log('production binding: authoritative sources tracked');
