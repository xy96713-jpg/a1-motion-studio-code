import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { changedNeeds, needPrint, refreshReadingWindows, retireChangedNeeds } from '../apps/studio-next/src/lib/recipe-board/materials.mjs';
import { READ_WINDOW_VERSION } from '../apps/studio-next/src/lib/recipe-board/page-capture.mjs';

const root = fs.mkdtempSync(path.join(process.env.TMPDIR, 'reading-stale-'));
const cfg = { dataDir: root, sourceRoot: root, repoRoot: root }, id = 'fixture';
const dir = path.join(root, 'projects', id, 'materials');
const put = (f, x) => fs.writeFileSync(f, JSON.stringify(x, null, 2) + '\n');
const read = f => fs.readFileSync(f);
try {
  fs.mkdirSync(dir, { recursive: true });
  put(path.join(root, 'projects', id, 'project.json'), { id });
  const source = fileURLToPath(new URL('./fixtures/hairline/exploded-400x320.png', import.meta.url));
  const full = path.join(root, 'page-full.png');
  const r = spawnSync('ffmpeg', ['-v','error','-y','-i',source,'-vf','scale=1920:1080','-frames:v','1',full], { encoding:'utf8' });
  assert.equal(r.status, 0, r.stderr);
  put(path.join(root, 'archive.json'), { files: { fullPage: full }, pageHeight: 1080, places: {} });
  const old = { shotId:'B01', kind:'news', original:'old' };
  const current = { ...old, original:'changed' };
  const b02 = { shotId:'B02', kind:'news', original:'valid' };
  const s1 = { shotId:'B03', scene:1, kind:'news', original:'valid scene' };
  const s2 = { shotId:'B03', scene:2, kind:'news', original:'old scene' };
  const windowFile = key => path.join(root, `${key}-window.png`);
  const binding = (n, key) => { fs.copyFileSync(source, windowFile(key)); return { needPrint:needPrint(n), archive:{ fullPage:full, window:{ file:windowFile(key), version:1, term:null, old:'preserve' } } }; };
  const initial = { shots: { B01:binding(old,'B01'), B02:binding(b02,'B02'), 'B03~1':binding(s1,'B03~1'), 'B03~2':binding(s2,'B03~2') } };
  const bindings = path.join(dir,'bindings.json'), approvals = path.join(dir,'approvals.json');
  put(path.join(dir,'needs.json'), { needs:[current,b02,s1,{...s2,original:'changed scene'}] });
  put(bindings,initial); put(approvals,{ batches:[{items:[{shotId:'B01',status:'fetched',needPrint:needPrint(old)}]}] });
  assert.deepEqual(new Set(changedNeeds(cfg,id)), new Set(['B01','B03~2']));
  assert.throws(() => retireChangedNeeds(cfg,id), /disabled/);
  const approvalBefore = read(approvals), stale1 = read(windowFile('B01')), stale2 = read(windowFile('B03~2'));
  const b02Before = read(windowFile('B02')), sceneBefore = read(windowFile('B03~1'));
  const done = await refreshReadingWindows(cfg,id,{ only:new Set(['B01','B02']) });
  assert.deepEqual(done,['B02']);
  const after = JSON.parse(read(bindings));
  assert.deepEqual(after.shots.B01,initial.shots.B01);
  assert.deepEqual(after.shots['B03~2'],initial.shots['B03~2']);
  assert.deepEqual(after.shots['B03~1'],initial.shots['B03~1']);
  assert.deepEqual(read(windowFile('B01')),stale1); assert.deepEqual(read(windowFile('B03~2')),stale2);
  assert.deepEqual(read(windowFile('B03~1')),sceneBefore); assert.deepEqual(read(approvals),approvalBefore);
  assert.notDeepEqual(read(windowFile('B02')),b02Before);
  assert.equal(after.shots.B02.archive.window.version,READ_WINDOW_VERSION);
  assert.deepEqual(await refreshReadingWindows(cfg,id,{only:new Set(['B02'])}),[]);
  assert.deepEqual(await refreshReadingWindows(cfg,id,{only:new Set(['B03~2'])}),[]);
  assert.deepEqual(await refreshReadingWindows(cfg,id,{only:new Set(['B03~1'])}),['B03~1']);
  assert.notDeepEqual(read(windowFile('B03~1')),sceneBefore);
  assert.deepEqual(read(windowFile('B03~2')),stale2);
  assert.deepEqual(JSON.parse(read(bindings)).shots['B03~2'],initial.shots['B03~2']);
  assert.deepEqual(read(approvals),approvalBefore);
  const reset = JSON.parse(read(bindings)); reset.shots.B02 = initial.shots.B02; put(bindings, reset);
  fs.copyFileSync(source, windowFile('B02'));
  assert.deepEqual(await refreshReadingWindows(cfg,id), ['B02']);
  assert.deepEqual(read(windowFile('B01')),stale1);
  assert.deepEqual(read(windowFile('B03~2')),stale2);
  assert.deepEqual(JSON.parse(read(bindings)).shots.B01,initial.shots.B01);
  assert.deepEqual(read(approvals),approvalBefore);
  assert.throws(() => retireChangedNeeds(cfg,id), /disabled/);
  console.log('refreshReadingWindows: stale isolation, active refresh, scene, only, repeat, global guard PASS');
} finally { fs.rmSync(root,{recursive:true,force:true}); }
