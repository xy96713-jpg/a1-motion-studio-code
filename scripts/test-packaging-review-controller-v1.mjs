import assert from "node:assert/strict";
import {applyPackagingReviewDecision, assertPackagingReviewState, packagingReviewBinding, packagingProductionAllowed, reconcilePackagingReviewState, advancePackageMotionIr} from "../apps/studio-next/src/lib/a1-packaging-review-controller-v1.mjs";
import {anchorCompositeCacheKey, generationInputHash, generationJobIdentity} from "../apps/studio-next/src/lib/a1-generation-cache-v1.mjs";
import {writeGenerationRuntimeSidecar} from "../apps/studio-next/src/lib/a1-generation-runtime-sidecar-v1.mjs";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const proof = {contract: "A1ReferenceConditionedPackagingAnchorProof/v1", status: "READY_FOR_REVIEW", eventIds: ["packaging-event-01"], planSha256: "p".repeat(64), comparisonProofSha256: "c".repeat(64), anchors: [{eventId: "packaging-event-01", publicUrl: "/clean.png", editableTextSpecSha256: "e".repeat(64), imagegenMaster: {sourceSha256: "m".repeat(64)}}]};
const base = {workspaceSha256: "w".repeat(64), production: {packagingBeatPlan: {sha256: "p".repeat(64)}, packagingAnchorProof: proof}};
const pending = reconcilePackagingReviewState({...base});
const applied = applyPackagingReviewDecision(pending, "approved", {now: "2026-08-04T00:00:00.000Z"});
assert.equal(applied.decision.decision, "approved");
assert.equal(packagingProductionAllowed(applied.workspace), false, "missing/unknown master provenance must not unlock production");
assert.throws(() => advancePackageMotionIr(applied.workspace, {shotId: null, now: "2026-08-04T00:00:00.500Z"}), /package-motion-ir-assembly-approval-required/u);
assertPackagingReviewState(applied.workspace);
const replay = applyPackagingReviewDecision(applied.workspace, "approved", {now: "2026-08-04T00:00:01.000Z"});
assert.equal(replay.idempotent, true);
assert.throws(() => applyPackagingReviewDecision(applied.workspace, "structure-revise-required"), /immutable/u);
const changed = structuredClone(applied.workspace);
changed.production.packagingBeatPlan.sha256 = "q".repeat(64);
const stale = reconcilePackagingReviewState(changed);
assert.equal(stale.production.packagingReview.status, "STALE");
assert.equal(stale.production.packagingReview.currentDecision, null);
assert.equal(generationInputHash({a: 1}), generationInputHash({a: 1}));
assert.notEqual(generationInputHash({a: 1}), generationInputHash({a: 1, variantNonce: "v2"}));
assert.equal(generationJobIdentity({projectId: "p", eventId: "e"}), generationJobIdentity({projectId: "p", eventId: "e"}));
assert.notEqual(anchorCompositeCacheKey({masterSha256: "a", styleBriefSha256: "b", compositorRevision: 1}), anchorCompositeCacheKey({masterSha256: "a", styleBriefSha256: "b", compositorRevision: 2}));
const temp = fs.mkdtempSync(path.join(os.tmpdir(), "a1-sidecar-test-"));
const first = writeGenerationRuntimeSidecar(temp, {phase: "running", running: 1, wallClockMs: 10});
const second = writeGenerationRuntimeSidecar(temp, {phase: "running", running: 1, wallClockMs: 10, heartbeatAt: first.path ? JSON.parse(fs.readFileSync(first.path, "utf8")).heartbeatAt : null});
assert.equal(first.written, true);
assert.equal(second.written, false);
fs.rmSync(temp, {recursive: true, force: true});
console.log("A1 packaging review/cache/sidecar controller PASS");
