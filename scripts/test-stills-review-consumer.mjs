import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import crypto from 'node:crypto';
import sharp from '../apps/studio-next/node_modules/sharp/lib/index.js';
import * as S from '../apps/studio-next/src/lib/recipe-board/stills.mjs';
import {buildStillReviewPack} from '../apps/studio-next/src/lib/recipe-board/still-review-pack.mjs';
import {writeTask,submitTaskAnswer,readTask,reviewSubmissionStatus,runCodexTask} from '../apps/studio-next/src/lib/recipe-board/agenttask.mjs';
const hash=x=>crypto.createHash('sha256').update(x).digest('hex');
test('formal still review consumer attaches roles before write, preserves task bytes and enforces receipts and material integrity',async()=>{
 const root=fs.mkdtempSync(path.join(os.homedir(),'.hermes/cache/scratch/still-review-consumer-')),cfg={dataDir:root},id='fixture';
 fs.mkdirSync(path.join(root,'projects',id),{recursive:true});
 fs.writeFileSync(path.join(root,'projects',id,'project.json'),JSON.stringify({id}));
 const frame=path.join(root,'frame.png'),source=path.join(root,'source.json');
 await sharp({create:{width:192,height:108,channels:3,background:'#445566'}}).png().toFile(frame);
 fs.writeFileSync(source,'{}');
 writeTask(cfg,id,'stills',{inputHash:'fixture-writer'});
 const candidate=path.join(root,'candidate.json');fs.writeFileSync(candidate,JSON.stringify({sourceTaskInputHash:'fixture-writer',code:'fixture'}));
 submitTaskAnswer(cfg,id,'stills',candidate,{env:{CODEX_THREAD_ID:'fixture-writer'}});
 const opts={root,outDir:path.join(root,'pack'),expectedBeats:['B01'],inputFiles:[source],shots:[{beat:'B01',frame}]};
 const initial=await buildStillReviewPack(opts);
 opts.shots[0].renderBinding={inputHash:initial.inputHash,frameHash:hash(fs.readFileSync(frame))};
 opts.shots[0].geometry={frameHash:opts.shots[0].renderBinding.frameHash,method:'fixture geometry, not a visual inspection',boxes:[{id:'title',x:10,y:10,w:50,h:20}]};
 const pack=await buildStillReviewPack(opts);
 const task={schema:'work/recipe-board-v1/routing/taste-review.schema.json',forAnswer:hash(fs.readFileSync(candidate)).slice(0,16),input:{taskMode:'stills'},images:[frame]};
 assert.equal(typeof S.prepareStillReviewTasks,'function','formal still review consumer must exist');
 const first=await S.prepareStillReviewTasks(cfg,id,{task,pack,filmBeats:['B01','B02'],forCheck:'check'});
 assert.equal(first.ok,true);assert.equal(first.created,true);
 const tp=path.join(root,'projects/fixture/tasks/stills-taste.task.json'),bytes=fs.readFileSync(tp);
 const saved=readTask(cfg,id,'stills-taste');
 assert.equal(saved.schema,task.schema);assert.equal(saved.independentReview.writerStep,'stills');
 assert.equal(saved.input.stillReviewPack.shots[0].version.status,'bound');
 assert.equal(saved.images.length,3);assert.deepEqual(saved.input.filmCoverage.missing,['B02']);
 assert.equal(saved.input.stillReviewPack.visualInspection,'unknown');
 assert.equal((await S.prepareStillReviewTasks(cfg,id,{task,pack,filmBeats:['B01','B02'],forCheck:'check'})).created,false);
 assert.deepEqual(fs.readFileSync(tp),bytes,'polling must not refresh timestamp or invalidate receipt');
 const review=path.join(root,'review.json');fs.writeFileSync(review,JSON.stringify({beats:[{beat:'B01',score:4,issue:null}]}));
 assert.throws(()=>submitTaskAnswer(cfg,id,'stills-taste',review,{env:{CODEX_THREAD_ID:'fixture-writer'}}),/different threads/);
 for(const step of ['stills-taste','stills-taste-2']) {
  submitTaskAnswer(cfg,id,step,review,{env:{CODEX_THREAD_ID:`fixture-${step}`}});
  assert.equal(reviewSubmissionStatus(cfg,id,step,readTask(cfg,id,step),{writerStep:'stills'}).ok,true);
 }
 assert.equal(S.stillReviewMaterialsStatus(saved).ok,true);
 fs.appendFileSync(pack.shots[0].images['layout-overlay'].path,'stale');
 assert.equal(S.stillReviewMaterialsStatus(saved).ok,false);
 await assert.rejects(runCodexTask(cfg,'stills-taste',saved,'beats'),/materials invalid before dispatch/);
 assert.throws(()=>submitTaskAnswer(cfg,id,'stills-taste',review,{env:{CODEX_THREAD_ID:'fixture-reviewer'}}),/material/i);
 const blocked=await S.prepareStillReviewTasks(cfg,id,{task,pack,filmBeats:['B01'],forCheck:'check'});
 assert.equal(blocked.ok,false);assert.deepEqual(fs.readFileSync(tp),bytes);
 const unknown=structuredClone(pack);unknown.shots[0].version.status='unknown';
 assert.equal(S.stillReviewMaterialsStatus({input:{stillReviewPack:unknown}}).ok,false);
 console.log('fixture consumer: 2 independent receipt chains verified; no production visual approval');
});
