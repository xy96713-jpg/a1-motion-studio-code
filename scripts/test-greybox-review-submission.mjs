import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { greyboxInput, greyboxReview, greyboxReviewPassed, eventReviewEvidence } from '../apps/studio-next/src/lib/recipe-board/greybox.mjs';
import { writeTask, submitTaskAnswer, taskPaths } from '../apps/studio-next/src/lib/recipe-board/agenttask.mjs';
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'greybox-submission-'));
const cfg = { repoRoot: process.cwd(), dataDir: root }, id = 'receipt-test';
const project = path.join(root, 'projects', id), tasks = path.join(project, 'tasks'), dir = path.join(project, 'out/greybox');
const write = (f, v) => { fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, JSON.stringify(v)); };
const hash = f => crypto.createHash('sha256').update(fs.readFileSync(f)).digest('hex').slice(0, 16);
const read = f => JSON.parse(fs.readFileSync(f));
try {
  fs.mkdirSync(dir, { recursive: true });
  fs.symlinkSync(path.join(process.cwd(), 'work/recipe-board-v1/routing'), path.join(root, 'routing'));
  write(path.join(project, 'project.json'), { id });
  write(path.join(project, 'shots/B01.json'), { shotId: 'B01', recipe: 'evidence-card', motion: { duration: 2 } });
  const design = { beats: [{ beat: 'B01', activeRevision: true, directorIntent: { eventTimes: { start: 0, key: 0.5, end: 1.5 }, start: 'hold', change: 'hold', end: 'hold' } }] };
  write(path.join(tasks, 'filmdesign.answer.json'), design);
  write(path.join(tasks, 'filmdesign.check.json'), { ok: true, answerHash: hash(path.join(tasks, 'filmdesign.answer.json')) });
  writeTask(cfg, id, 'greybox', { forInput: 'input-v1' });
  const writer = path.join(root, 'writer.json'); write(writer, { beats: [] });
  // Direct canonical writing is intentionally the negative fixture, not a claimed blind review.
  fs.copyFileSync(writer, path.join(tasks, 'greybox.answer.json'));
  write(path.join(tasks, 'greybox.check.json'), { ok: true, answerHash: 'checked-greybox-v1' });
  const ff = spawnSync('ffmpeg', ['-y', '-loglevel', 'error', '-f', 'lavfi', '-i', 'color=c=blue:s=32x32:r=4:d=2', '-pix_fmt', 'yuv420p', path.join(dir, 'greybox.mp4')]);
  assert.equal(ff.status, 0, ff.stderr?.toString());
  const inputs = await greyboxInput(cfg, id);
  const events = eventReviewEvidence(dir, inputs, 'checked-greybox-v1');
  assert.equal(events[0].status, 'measured');
  writeTask(cfg, id, 'greybox-review', { forGreybox: 'checked-greybox-v1', forAnswer: hash(writer), independentReview: { writerStep: 'greybox' }, input: { events } });
  const review = path.join(root, 'review.json');
  write(review, { scores: Object.fromEntries(['arc', 'telling', 'layout', 'colour', 'seams', 'motion'].map(k => [k, 4])), issues: [], events: events.map(e => ({ beat: e.beat, binding: e.binding, verdict: 'pass', observed: 'Synthetic hold fixture stays blue throughout.' })) });
  fs.copyFileSync(review, path.join(tasks, 'greybox-review.answer.json'));
  const result = await greyboxReview(cfg, id);
  assert.equal(result.state, 'rejected', 'author-written answer without submission receipts must not pass');
  assert.match(result.errors.join('\n'), /submission|independent/);
  submitTaskAnswer(cfg, id, 'greybox', writer, { env: { CODEX_THREAD_ID: 'fixture-writer' } });
  assert.throws(() => submitTaskAnswer(cfg, id, 'greybox-review', review, { env: { CODEX_THREAD_ID: 'fixture-writer' } }), /different threads/);
  submitTaskAnswer(cfg, id, 'greybox-review', review, { env: { CODEX_THREAD_ID: 'fixture-reviewer' } });
  assert.equal((await greyboxReview(cfg, id)).state, 'passed');
  assert.equal(greyboxReviewPassed(cfg, id), true);
  const assertBlocked = async label => {
    assert.equal(greyboxReviewPassed(cfg, id), false, label);
    assert.notEqual((await greyboxReview(cfg, id)).state, 'passed', label);
  };
  const rp = taskPaths(cfg, id, 'greybox-review');
  const accepted = fs.readFileSync(rp.answer), taskBytes = fs.readFileSync(rp.task);
  write(rp.answer, { ...read(rp.answer), note: 'changed after receipt' });
  await assertBlocked('tampered review invalidates cached gate');
  fs.writeFileSync(rp.answer, accepted);
  write(rp.task, { ...read(rp.task), changedTask: true });
  await assertBlocked('stale review-task receipt invalidates cached gate');
  fs.writeFileSync(rp.task, taskBytes);
  const wp = taskPaths(cfg, id, 'greybox'), writerTask = fs.readFileSync(wp.task);
  write(wp.task, { ...read(wp.task), forInput: 'input-v2' });
  await assertBlocked('stale writer task invalidates cached gate');
  fs.writeFileSync(wp.task, writerTask);
  write(wp.answer, { beats: ['changed after receipt'] });
  await assertBlocked('writer answer changed after review');
  fs.copyFileSync(writer, wp.answer);
  // Generate the normal review task through the actual consumer, not only a hand-built fixture.
  fs.rmSync(rp.task); fs.rmSync(path.join(tasks, 'greybox-review.gate.json'));
  assert.equal((await greyboxReview(cfg, id)).state, 'review');
  assert.equal(read(rp.task).forAnswer, hash(writer));
  assert.equal(read(rp.task).independentReview.writerStep, 'greybox');
  submitTaskAnswer(cfg, id, 'greybox-review', review, { env: { CODEX_THREAD_ID: 'fixture-reviewer' } });
  assert.equal((await greyboxReview(cfg, id)).state, 'passed');
  const rejected = read(review); rejected.events[0].verdict = 'fail'; write(review, rejected);
  submitTaskAnswer(cfg, id, 'greybox-review', review, { env: { CODEX_THREAD_ID: 'fixture-reviewer' } });
  await assertBlocked('newly submitted failing answer must not reuse old pass');
  design.beats[0].activeRevision = false;
  write(path.join(tasks, 'filmdesign.answer.json'), design);
  write(path.join(tasks, 'filmdesign.check.json'), { ok: true, answerHash: hash(path.join(tasks, 'filmdesign.answer.json')) });
  assert.equal(greyboxReviewPassed(cfg, id), true, 'historical unscoped gate stays approved');
  assert.equal((await greyboxReview(cfg, id)).state, 'passed', 'historical design is not reopened');
  console.log('greybox independent submission: direct-answer rejection, distinct-thread pass, stale task/answer/cache rejection, generated task, legacy compatibility passed');
} finally { fs.rmSync(root, { recursive: true, force: true }); }
