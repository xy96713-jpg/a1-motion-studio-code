import assert from 'node:assert/strict';
import { mkdtemp, rm, readFile } from 'node:fs/promises';
import path from 'node:path';
import * as hairline from '../apps/studio-next/src/lib/recipe-board/hairline-still.mjs';
const { prepareFixedHairline } = hairline;
const dir = await mkdtemp(path.join(process.env.TMPDIR, 'hairline-test-'));
try {
  const spec = {key:'hairline_test',figure:'exploded',phaseMs:192,intensity:0.8};
  const a = await prepareFixedHairline(dir,spec);
  const original = await readFile(a.file);
  assert.equal(typeof hairline.consumePreparedHairline, 'function');
  assert.equal(await hairline.consumePreparedHairline(dir, spec, a), a.file);
  await assert.rejects(hairline.consumePreparedHairline(dir, {...spec, phaseMs:193}, a));
  await assert.rejects(hairline.consumePreparedHairline(dir, spec, {...a}));
  await (await import('node:fs/promises')).writeFile(a.file, 'changed');
  await assert.rejects(hairline.consumePreparedHairline(dir, spec, a), /changed/i);
  await (await import('node:fs/promises')).writeFile(a.file, original);
  const victim = path.join(dir, 'victim.txt');
  await (await import('node:fs/promises')).writeFile(victim, 'do not truncate');
  await (await import('node:fs/promises')).unlink(a.file);
  await (await import('node:fs/promises')).link(victim, a.file);
  const b = await prepareFixedHairline(dir,spec);
  assert.equal((await readFile(victim)).toString(), 'do not truncate');
  assert.deepEqual(await readFile(b.file), original);
  await (await import('node:fs/promises')).unlink(b.file);
  await (await import('node:fs/promises')).symlink(victim, b.file);
  await prepareFixedHairline(dir,spec);
  assert.equal((await readFile(victim)).toString(), 'do not truncate');
  assert.deepEqual(await readFile(b.file), original);
  const c = await prepareFixedHairline(dir,{...spec,intensity:0.1});
  assert.notDeepEqual(await readFile(a.file),await readFile(c.file));
  await (await import('node:fs/promises')).unlink(a.file);
  await (await import('node:fs/promises')).mkdir(a.file);
  await assert.rejects(prepareFixedHairline(dir,spec));
  const left = await (await import('node:fs/promises')).readdir(path.dirname(a.file));
  assert.equal(left.filter(n => n.endsWith('.tmp')).length, 0, 'failed rename cleans its exclusive temporary file');
  await assert.rejects(prepareFixedHairline(dir,{...spec,phaseMs:-1}),/phase/i);
  console.log('fixed phase: deterministic real Hairline PNG; intensity changes pixels; invalid phase rejected');
} finally { await rm(dir,{recursive:true,force:true}); }
